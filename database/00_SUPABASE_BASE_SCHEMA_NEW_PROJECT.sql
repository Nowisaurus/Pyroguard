-- ----------------------------------------------------------------------------
-- C. ROW LEVEL SECURITY - owners manage their own records; active admins read.
--    (01_SUPABASE_FINAL_SYNC_FIX.sql then adds Home 1 member access.)
-- ----------------------------------------------------------------------------
DO $rls$
DECLARE t text;
BEGIN
    -- Own-row tables the app reads AND writes (onboarding, settings).
    FOREACH t IN ARRAY ARRAY['homes','stakeholders','emergency_contacts','safety_setups',
                             'user_preferences','pyroguard_notification_preferences']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS pyroguard_own_rows ON public.%I', t);
        EXECUTE format('CREATE POLICY pyroguard_own_rows ON public.%I FOR ALL TO authenticated '
                       'USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()))', t);
        EXECUTE format('DROP POLICY IF EXISTS pyroguard_admin_read ON public.%I', t);
        EXECUTE format('CREATE POLICY pyroguard_admin_read ON public.%I FOR SELECT TO authenticated '
                       'USING (public.pg_ticket_admin())', t);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO authenticated', t);
    END LOOP;

    -- History/evidence the app inserts for its own account and reads back.
    FOREACH t IN ARRAY ARRAY['sensor_history','event_history','camera_history','camera_events',
                             'audio_sessions','emergency_action_logs']
    LOOP
        EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
        EXECUTE format('DROP POLICY IF EXISTS pyroguard_own_read ON public.%I', t);
        EXECUTE format('CREATE POLICY pyroguard_own_read ON public.%I FOR SELECT TO authenticated '
                       'USING (user_id = (SELECT auth.uid()) OR public.pg_ticket_admin())', t);
        EXECUTE format('DROP POLICY IF EXISTS pyroguard_own_insert ON public.%I', t);
        EXECUTE format('CREATE POLICY pyroguard_own_insert ON public.%I FOR INSERT TO authenticated '
                       'WITH CHECK (user_id = (SELECT auth.uid()))', t);
        EXECUTE format('DROP POLICY IF EXISTS pyroguard_own_sync_update ON public.%I', t);
        EXECUTE format('CREATE POLICY pyroguard_own_sync_update ON public.%I FOR UPDATE TO authenticated '
                       'USING (user_id = (SELECT auth.uid())) WITH CHECK (user_id = (SELECT auth.uid()))', t);
        EXECUTE format('GRANT SELECT, INSERT, UPDATE ON public.%I TO authenticated', t);
    END LOOP;

    -- Hardware state written by Edge Functions (service role); owners/admins read.
