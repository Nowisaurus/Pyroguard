        RAISE EXCEPTION
            'Author must match current user';
    END IF;

    IF NEW.internal
       AND NOT public.pg_ticket_admin()
    THEN
        RAISE EXCEPTION
            'Only administrators can create internal notes';
    END IF;

    RETURN NEW;

END;
$$;


