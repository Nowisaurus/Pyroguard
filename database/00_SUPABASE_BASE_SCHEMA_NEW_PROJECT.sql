CREATE OR REPLACE FUNCTION public.pg_ticket_event_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN

    IF TG_OP = 'INSERT' THEN

        INSERT INTO public.support_ticket_events (
            ticket_id,
            actor_id,
            action,
            changes
        )
        VALUES (
            NEW.id,
            auth.uid(),
            'created',
            jsonb_build_object(
                'severity', NEW.severity,
                'category', NEW.category
            )
        );

    ELSIF ROW(
        NEW.status,
        NEW.severity,
        NEW.assigned_to,
        NEW.resolution_notes
    ) IS DISTINCT FROM ROW(
        OLD.status,
        OLD.severity,
        OLD.assigned_to,
        OLD.resolution_notes
    ) THEN

        INSERT INTO public.support_ticket_events (
            ticket_id,
            actor_id,
            action,
            changes
        )
        VALUES (
            NEW.id,
            auth.uid(),
            'updated',
            jsonb_build_object(
                'old_status', OLD.status,
                'new_status', NEW.status,
                'old_severity', OLD.severity,
                'new_severity', NEW.severity,
                'old_assigned_to', OLD.assigned_to,
                'new_assigned_to', NEW.assigned_to,
                'resolution_notes_changed',
                NEW.resolution_notes IS DISTINCT FROM OLD.resolution_notes
            )
        );

    END IF;

    RETURN NEW;

END;
$$;


