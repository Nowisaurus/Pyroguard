-- ============================================================================
-- 9. SESSION IDENTITY REPAIR
-- ============================================================================

CREATE OR REPLACE FUNCTION public.pyroguard_save_session(
    session_event TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
    uid UUID := auth.uid();
    u auth.users%ROWTYPE;
    a public.admin_accounts%ROWTYPE;
    role_name TEXT;
    now_at TIMESTAMPTZ := NOW();
    result JSONB;
BEGIN

    IF uid IS NULL THEN
        RAISE EXCEPTION 'Authentication required';
    END IF;

    IF session_event IS NOT NULL
       AND session_event NOT IN (
           'homeowner_login',
           'homeowner_logout',
           'admin_login',
           'admin_logout'
       )
    THEN
        RAISE EXCEPTION 'Invalid session event';
    END IF;

    SELECT *
    INTO u
    FROM auth.users
    WHERE id = uid;

    IF u.id IS NULL
       OR (
           u.banned_until IS NOT NULL
           AND u.banned_until > now_at
       )
    THEN
        RAISE EXCEPTION 'Account unavailable';
    END IF;

    SELECT *
    INTO a
    FROM public.admin_accounts
    WHERE user_id = uid;

    IF a.user_id IS NOT NULL THEN

        IF NOT a.active
           OR LOWER(a.email) <> LOWER(u.email)
           OR a.admin_role NOT IN (
               'administrator',
               'head_developer'
           )
        THEN
            RAISE EXCEPTION
                'Administrator registry mismatch';
        END IF;

        role_name := a.admin_role;

    ELSE

        IF COALESCE(
            u.raw_app_meta_data ->> 'role',
            ''
        ) IN (
            'administrator',
            'head_developer'
        )
        OR COALESCE(
            u.raw_app_meta_data ->> 'pyroguard_admin',
            'false'
        ) = 'true'
        THEN
            RAISE EXCEPTION
                'Administrator registry required';
        END IF;

        role_name := 'homeowner';

    END IF;

    IF role_name = 'homeowner'
       AND u.email_confirmed_at IS NULL
    THEN
        RAISE EXCEPTION
            'Confirm your email before completing registration';
    END IF;

    IF session_event IS NOT NULL
       AND (
           (
               role_name = 'homeowner'
               AND session_event LIKE 'admin_%'
           )
           OR
           (
               role_name <> 'homeowner'
               AND session_event LIKE 'homeowner_%'
           )
       )
    THEN
        RAISE EXCEPTION 'Session role mismatch';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM public.profiles
        WHERE user_id = uid
          AND (
              account_status <> 'active'
              OR account_role <> role_name
          )
    )
    OR EXISTS (
        SELECT 1
        FROM public.account_identities
        WHERE user_id = uid
          AND (
              account_status <> 'active'
              OR account_role <> role_name
          )
    )
    THEN
        RAISE EXCEPTION
            'Account role/status requires administrator repair';
    END IF;

    INSERT INTO public.profiles (
        id,
        user_id,
        email,
        full_name,
        phone,
        account_role,
        account_status,
        created_at,
        updated_at
    )
    VALUES (
        uid,
        uid,
        u.email,
        COALESCE(
            a.display_name,
            u.raw_user_meta_data ->> 'full_name',
            u.raw_user_meta_data ->> 'name'
        ),
        u.raw_user_meta_data ->> 'phone_number',
        role_name,
        'active',
        u.created_at,
        now_at
    )
    ON CONFLICT (user_id)
    DO NOTHING;

    INSERT INTO public.account_identities (
        user_id,
        email,
        display_name,
        phone,
        account_role,
        account_status,
        auth_provider,
        email_confirmed,
        event,
        logged_in_at,
        logged_out_at,
        mysql_synced,
        created_at,
        updated_at
    )
    VALUES (
        uid,
        u.email,
        COALESCE(
            a.display_name,
            u.raw_user_meta_data ->> 'full_name',
            u.raw_user_meta_data ->> 'name'
        ),
        u.raw_user_meta_data ->> 'phone_number',
        role_name,
        'active',
        COALESCE(
            u.raw_app_meta_data ->> 'provider',
            'email'
        ),
        u.email_confirmed_at IS NOT NULL,
        session_event,
        CASE
            WHEN session_event LIKE '%_login'
            THEN now_at
        END,
        CASE
            WHEN session_event LIKE '%_logout'
            THEN now_at
        END,
        FALSE,
        u.created_at,
        now_at
    )
    ON CONFLICT (user_id)
    DO UPDATE SET
        email = EXCLUDED.email,
        email_confirmed = EXCLUDED.email_confirmed,
        event = COALESCE(
            EXCLUDED.event,
            public.account_identities.event
        ),
        logged_in_at = COALESCE(
            EXCLUDED.logged_in_at,
            public.account_identities.logged_in_at
        ),
        logged_out_at = COALESCE(
            EXCLUDED.logged_out_at,
            public.account_identities.logged_out_at
        ),
        mysql_synced = FALSE,
        updated_at = now_at;

    SELECT TO_JSONB(i)
    INTO result
    FROM public.account_identities i
    WHERE i.user_id = uid;

    RETURN result;

END;
$$;

REVOKE ALL
ON FUNCTION public.pyroguard_save_session(TEXT)
FROM PUBLIC, anon;

GRANT EXECUTE
ON FUNCTION public.pyroguard_save_session(TEXT)
TO authenticated;


