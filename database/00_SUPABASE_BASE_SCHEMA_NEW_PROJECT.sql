-- ----------------------------------------------------------------------------
-- B. ROLE FUNCTIONS + ADMINISTRATOR REGISTRATION (by e-mail, no fixed IDs)
-- ----------------------------------------------------------------------------
-- Verified role: an active admin_accounts row whose e-mail matches Auth, else
-- 'homeowner' for a normal account, else NULL (blocked/unknown/admin-marked
-- account without a registry row). Works as pyroguard_verified_role() too.
CREATE OR REPLACE FUNCTION public.pyroguard_verified_role(p_user uuid DEFAULT auth.uid())
RETURNS text LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = '' AS $$
DECLARE u auth.users%ROWTYPE; a public.admin_accounts%ROWTYPE;
BEGIN
    IF p_user IS NULL THEN RETURN NULL; END IF;
    SELECT * INTO u FROM auth.users WHERE id = p_user;
    IF u.id IS NULL OR (u.banned_until IS NOT NULL AND u.banned_until > now()) THEN RETURN NULL; END IF;
    SELECT * INTO a FROM public.admin_accounts WHERE user_id = p_user;
    IF a.user_id IS NOT NULL THEN
        IF a.active AND lower(a.email) = lower(u.email) THEN RETURN a.admin_role; END IF;
        RETURN NULL;
    END IF;
    IF coalesce(u.raw_app_meta_data ->> 'role', '') IN ('administrator','head_developer')
       OR coalesce(u.raw_app_meta_data ->> 'pyroguard_admin', 'false') = 'true' THEN
        RETURN NULL;   -- marked admin without a registry row: denied
    END IF;
    RETURN 'homeowner';
END;
$$;
REVOKE ALL ON FUNCTION public.pyroguard_verified_role(uuid) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.pyroguard_verified_role(uuid) TO authenticated, service_role;

CREATE OR REPLACE FUNCTION public.pg_ticket_admin()
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
    SELECT EXISTS (SELECT 1 FROM public.admin_accounts
                    WHERE user_id = auth.uid() AND active IS TRUE
                      AND admin_role IN ('administrator','head_developer'));
$$;
REVOKE ALL ON FUNCTION public.pg_ticket_admin() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.pg_ticket_admin() TO authenticated, service_role;

