-- PyroGuard v17 (2026-11-23): BFP e-mail address + log of incident reports sent to the BFP.
-- Panel/BFP feedback: the incident report (PDF) must be sendable to the BFP for their records.

ALTER TABLE public.emergency_contacts ADD COLUMN IF NOT EXISTS email text;
ALTER TABLE public.emergency_contacts DROP CONSTRAINT IF EXISTS emergency_contacts_email_format;
ALTER TABLE public.emergency_contacts ADD CONSTRAINT emergency_contacts_email_format
  CHECK (email IS NULL OR email = '' OR email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$');

CREATE TABLE IF NOT EXISTS public.pyroguard_bfp_report_emails (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  report_number text NOT NULL,
  bfp_email text NOT NULL,
  bfp_station text,
  cc_email text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','sent','failed')),
  provider text,
  error text,
  created_at timestamptz NOT NULL DEFAULT now(),
  sent_at timestamptz
);
CREATE INDEX IF NOT EXISTS pyroguard_bfp_report_emails_user_idx
  ON public.pyroguard_bfp_report_emails(user_id, created_at DESC);

ALTER TABLE public.pyroguard_bfp_report_emails ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "own bfp report emails" ON public.pyroguard_bfp_report_emails;
CREATE POLICY "own bfp report emails" ON public.pyroguard_bfp_report_emails
  FOR SELECT TO authenticated USING (user_id = auth.uid());
-- Rows are written only by the send-incident-report Edge Function (service role).
GRANT SELECT ON public.pyroguard_bfp_report_emails TO authenticated;
